<?php

namespace App\Http\Controllers\Api\Auth;

use App\Http\Controllers\Controller;
use App\Http\Services\Auth\TwoFactorService;
use App\Traits\ApiResponseTrait;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use OpenApi\Attributes as OA;

class TwoFactorController extends Controller
{
    use ApiResponseTrait;

    public function __construct(
        protected TwoFactorService $twoFactorService
    ) {
    }


    #[OA\Post(
        path: "/api/auth/two-factor/setup",
        summary: "Start Two-Factor Authentication Setup",
        description: "Start setting up TOTP-based two-factor authentication for the authenticated user. Returns a secret and an otpauth URL that can be used to generate an authenticator QR code. The setup must be confirmed within 10 minutes.",
        security: [["bearerAuth" => []]],
        tags: ["Authentication"],
        parameters: [
            new OA\Parameter(ref: "#/components/parameters/XLocale"),
        ],
        responses: [
            new OA\Response(
                response: 200,
                description: "Two-factor authentication setup started successfully.",
                content: new OA\JsonContent(
                    allOf: [
                        new OA\Schema(ref: "#/components/schemas/SuccessResponse"),
                        new OA\Schema(
                            properties: [
                                new OA\Property(
                                    property: "data",
                                    type: "object",
                                    properties: [
                                        new OA\Property(
                                            property: "secret",
                                            type: "string",
                                            description: "TOTP secret. Display this only during setup.",
                                            example: "JBSWY3DPEHPK3PXP"
                                        ),
                                        new OA\Property(
                                            property: "otpauth_url",
                                            type: "string",
                                            description: "Authenticator provisioning URI used to generate the QR code.",
                                            example: "otpauth://totp/MyApp:user@example.com?secret=JBSWY3DPEHPK3PXP&issuer=MyApp"
                                        ),
                                        new OA\Property(
                                            property: "expires_at",
                                            type: "string",
                                            format: "date-time",
                                            example: "2026-11-25T10:30:00+03:30"
                                        ),
                                    ]
                                )
                            ]
                        )
                    ]
                )
            ),
            new OA\Response(
                response: 401,
                description: "Invalid, expired, revoked, reused, or missing refresh token. Also returned when both refresh token sources are provided.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 409,
                description: "Two-factor authentication is already enabled.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 500,
                description: "Unexpected server error.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
        ]
    )]
    public function startSetup(Request $request): JsonResponse
    {
        $result = $this->twoFactorService->startSetup(
            $request->user()
        );

        if (!$result['status']) {
            return $this->error(
                $result['message'],
                $result['code']
            );
        }

        return $this->success(
            $result['data'] ?? null,
            $result['message'],
            $result['code']
        );
    }


    #[OA\Post(
        path: "/api/auth/two-factor/confirm",
        summary: "Confirm Two-Factor Authentication Setup",
        description: "Verify the TOTP code generated by the user's authenticator application. On successful verification, two-factor authentication is enabled and eight one-time recovery codes are generated. Recovery codes are returned only once.",
        security: [["bearerAuth" => []]],
        tags: ["Authentication"],
        parameters: [
            new OA\Parameter(ref: "#/components/parameters/XLocale"),
        ],
        requestBody: new OA\RequestBody(
            required: true,
            content: new OA\JsonContent(
                required: ["code"],
                properties: [
                    new OA\Property(
                        property: "code",
                        type: "string",
                        minLength: 6,
                        maxLength: 6,
                        pattern: "^[0-9]{6}$",
                        example: "123456"
                    ),
                ]
            )
        ),
        responses: [
            new OA\Response(
                response: 200,
                description: "Two-factor authentication enabled successfully. Eight one-time recovery codes are returned.",
                content: new OA\JsonContent(
                    allOf: [
                        new OA\Schema(ref: "#/components/schemas/SuccessResponse"),
                        new OA\Schema(
                            properties: [
                                new OA\Property(
                                    property: "data",
                                    type: "object",
                                    properties: [
                                        new OA\Property(
                                            property: "recovery_codes",
                                            type: "array",
                                            description: "Eight one-time recovery codes. Store them securely; they will not be returned again.",
                                            items: new OA\Items(
                                                type: "string",
                                                example: "A1B2C3D4E5"
                                            ),
                                            minItems: 8,
                                            maxItems: 8
                                        ),
                                    ]
                                )
                            ]
                        )
                    ]
                )
            ),
            new OA\Response(
                response: 400,
                description: "The setup does not exist or two-factor authentication is already enabled.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 401,
                description: "Invalid, expired, revoked, reused, or missing refresh token. Also returned when both refresh token sources are provided.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 410,
                description: "The two-factor setup has expired.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 422,
                description: "Invalid TOTP code or request validation failure.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ValidationErrorResponse"
                )
            ),
            new OA\Response(
                response: 500,
                description: "Unexpected server error.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
        ]
    )]
    public function confirmSetup(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'code' => ['required', 'string', 'digits:6'],
        ]);

        $result = $this->twoFactorService->confirmSetup(
            $request->user(),
            $validated['code']
        );

        if (!$result['status']) {
            return $this->error(
                $result['message'],
                $result['code']
            );
        }

        return $this->success(
            $result['data'] ?? null,
            $result['message'],
            $result['code']
        );
    }


    #[OA\Post(
        path: "/api/auth/two-factor/disable",
        summary: "Disable Two-Factor Authentication",
        description: "Disable two-factor authentication for the authenticated user. Requires the current password and either a valid authenticator code or an unused recovery code. All recovery codes are deleted after successful deactivation.",
        security: [["bearerAuth" => []]],
        tags: ["Authentication"],
        parameters: [
            new OA\Parameter(ref: "#/components/parameters/XLocale"),
        ],
        requestBody: new OA\RequestBody(
            required: true,
            content: new OA\JsonContent(
                required: ["password", "code"],
                properties: [
                    new OA\Property(
                        property: "password",
                        type: "string",
                        format: "password",
                        example: "CurrentPassword123"
                    ),
                    new OA\Property(
                        property: "code",
                        type: "string",
                        description: "A 6-digit authenticator code or a 10-character recovery code.",
                        example: "123456"
                    ),
                ]
            )
        ),
        responses: [
            new OA\Response(
                response: 200,
                description: "Two-factor authentication disabled successfully.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/SuccessResponse"
                )
            ),
            new OA\Response(
                response: 401,
                description: "Invalid, expired, revoked, reused, or missing refresh token. Also returned when both refresh token sources are provided.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 409,
                description: "Two-factor authentication is not enabled.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
            new OA\Response(
                response: 422,
                description: "Invalid current password, invalid authenticator or recovery code, or request validation failure.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ValidationErrorResponse"
                )
            ),
            new OA\Response(
                response: 500,
                description: "Unexpected server error.",
                content: new OA\JsonContent(
                    ref: "#/components/schemas/ErrorResponse"
                )
            ),
        ]
    )]
    public function disable(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'password' => ['required', 'string'],
            'code' => ['required', 'string'],
        ]);

        $result = $this->twoFactorService->disable(
            $request->user(),
            $validated['password'],
            $validated['code']
        );

        if (!$result['status']) {
            return $this->error(
                $result['message'],
                $result['code']
            );
        }

        return $this->success(
            $result['data'] ?? null,
            $result['message'],
            $result['code']
        );
    }
}
